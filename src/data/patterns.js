export function getRelatedPatterns(pattern, limit = 4) {
  return patterns
    .filter((candidate) => candidate.id !== pattern.id)
    .map((candidate) => {
      const sharedGoals = candidate.goals.filter((value) => pattern.goals.includes(value));
      const sharedModalities = candidate.modalities.filter((value) => pattern.modalities.includes(value));
      const sharedDomains = candidate.domains.filter((value) => pattern.domains.includes(value));
      const sharedUsers = candidate.users.filter((value) => pattern.users.includes(value));
      const score = sharedGoals.length * 4 + sharedModalities.length * 2 + sharedDomains.length * 2 + sharedUsers.length;
      return { pattern: candidate, score, sharedGoals, sharedModalities, sharedDomains, sharedUsers };
    })
    .filter((item) => item.score > 0)
    .sort((a, b) => b.score - a.score || a.pattern.id - b.pattern.id)
    .slice(0, limit);
}
